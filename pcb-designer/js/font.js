const parsed = {};
for (const [k, v] of Object.entries(G)) parsed[k] = v.split(';').map((s) => s.trim().split(/\s+/).map((p) => p.split(',').map(Number)));

// Returns polylines (mm) for a text centred on (x, y). size = cap height in mm.
export function textStrokes(text, x, y, size = 1.5, mirror = false) {
  const s = size / 6, adv = 5.5 * s;
  const str = String(text).toUpperCase();
  const width = str.length * adv - 1.5 * s;
  const lines = [];
  let cx = -width / 2;
  for (const ch of str) {
    const g = parsed[ch];
    if (g) for (const pl of g) lines.push(pl.map(([gx, gy]) => {
      const lx = cx + gx * s;
      return [x + (mirror ? -lx : lx), y - size / 2 + gy * s];
    }));
    cx += adv;
  }
  return lines;
}
export const strokeWidth = (size) => Math.max(0.12, size / 9);
